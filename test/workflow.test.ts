test("bounded scheduler runs jobs in parallel up to its limit", async () => {
  let active = 0;
  let maximum = 0;
  const seen: number[] = [];
  await runWithConcurrency([1, 2, 3, 4], 2, async (item) => {
    active++;
    maximum = Math.max(maximum, active);
    seen.push(item);
    await new Promise((resolve) => setTimeout(resolve, 5));
    active--;
  });
  assert.deepEqual(seen, [1, 2, 3, 4]);
  assert.equal(maximum, 2);
});

test("commit subjects use model intent, one issue reference, and one line", () => {
  assert.equal(
    commitSubject(
      12,
      "Fix retry handling for #12\nwithout losing state",
      "summary",
    ),
    "Fix retry handling for without losing state (#12)",
  );
  assert.equal(
    commitSubject(
      12,
      "Add preview whitespace regression tests (#12)",
      "summary",
    ),
    "Add preview whitespace regression tests (#12)",
  );
  assert.equal(
    commitSubject(12, "Fix\u0000\u001b terminal output", "summary"),
    "Fix terminal output (#12)",
  );
  assert.equal(
    commitSubject(12, undefined, "Clarify retry behavior after a restart"),
    "Clarify retry behavior after a restart (#12)",
  );
  assert.equal(commitSubject(12, "  \n ", ""), "Update implementation (#12)");
  const longIssueSubject = commitSubject(
    1234567890123456,
    "A".repeat(100),
    "summary",
  );
  assert.ok(Array.from(longIssueSubject).length <= 70);
  assert.equal(longIssueSubject.endsWith(" (#1234567890123456)"), true);
});

test("publication text is structured and clearly attributed", () => {
  const body = pullRequestBody(
    12,
    "Add the filter controls.",
    "npm test\n3 passed",
  );
  assert.match(body, /^## Implementation summary/m);
  assert.match(body, /## Validation/);
  assert.match(body, /<details>\n<summary>Validation results<\/summary>/);
  assert.match(body, /```text\nnpm test\n3 passed\n```/);
  assert.match(body, /Closes #12/);
  assert.match(
    body,
    /Generated by \[Louibot\]\(https:\/\/github\.com\/rkkautsar\/louibot\)/,
  );
  assert.match(body, /<!-- louibot:12 -->/);
});

