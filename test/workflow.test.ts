import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import test from "node:test";
import {
  commitSubject,
  clarificationComment,
  issuePhase,
  pullRequestBody,
  readPullRequestTemplate,
  revisionComment,
  runWithConcurrency,
  validationDetails,
} from "../src/workflow.js";
import type { Job, JobStatus } from "../src/store.js";

function job(status: JobStatus, outcome?: Job["outcome"]): Job {
  return {
    issue: 1,
    title: "Issue",
    body: "",
    status,
    branch: "louibot/issue-1",
    worktree: "/tmp/issue-1",
    revision: 0,
    cost: 0,
    last: "",
    events: [],
    feedback: "",
    rounds: 0,
    outcome,
  };
}

test("active and review states keep the active issue label", () => {
  for (const status of ["coding", "queued", "review"]) {
    assert.equal(issuePhase(job(status)), "ready", status);
  }
});

test("clarification, failures, and explicit stops use the blocked label", () => {
  for (const status of ["clarification", "failed"]) {
    assert.equal(issuePhase(job(status)), "blocked", status);
  }
  assert.equal(issuePhase(job("queued"), true), "blocked");
});

test("only a merged completion gets the done label", () => {
  assert.equal(issuePhase(job("done", "merged")), "done");
  assert.equal(issuePhase(job("done", "closed")), "closed");
  assert.equal(issuePhase(job("done")), "closed");
});

test("bounded scheduler runs jobs in parallel up to its limit", async () => {
  let active = 0;
  let maximum = 0;
  const seen: number[] = [];
  await runWithConcurrency([1, 2, 3, 4], 2, async (item) => {
    active++;
    maximum = Math.max(maximum, active);
    seen.push(item);
    await new Promise((resolve) => setTimeout(resolve, 5));
    active--;
  });
  assert.deepEqual(seen, [1, 2, 3, 4]);
  assert.equal(maximum, 2);
});

test("commit subjects use model intent, one issue reference, and one line", () => {
  assert.equal(
    commitSubject(
      12,
      "Fix retry handling for #12\nwithout losing state",
      "summary",
    ),
    "Fix retry handling for without losing state (#12)",
  );
  assert.equal(
    commitSubject(
      12,
      "Add preview whitespace regression tests (#12)",
      "summary",
    ),
    "Add preview whitespace regression tests (#12)",
  );
  assert.equal(
    commitSubject(12, "Fix\u0000\u001b terminal output", "summary"),
    "Fix terminal output (#12)",
  );
  assert.equal(
    commitSubject(12, undefined, "Clarify retry behavior after a restart"),
    "Clarify retry behavior after a restart (#12)",
  );
  assert.equal(commitSubject(12, "  \n ", ""), "Update implementation (#12)");
  const longIssueSubject = commitSubject(
    1234567890123456,
    "A".repeat(100),
    "summary",
  );
  assert.ok(Array.from(longIssueSubject).length <= 70);
  assert.equal(longIssueSubject.endsWith(" (#1234567890123456)"), true);
});

test("publication text is structured and clearly attributed", () => {
  const body = pullRequestBody(
    12,
    "Add the filter controls.",
    "npm test\n3 passed",
  );
  assert.match(body, /^## Implementation summary/m);
  assert.match(body, /## Validation/);
  assert.match(body, /<details>\n<summary>Validation results<\/summary>/);
  assert.match(body, /```text\nnpm test\n3 passed\n```/);
  assert.match(body, /Closes #12/);
  assert.match(
    body,
    /Generated by \[Louibot\]\(https:\/\/github\.com\/rkkautsar\/louibot\)/,
  );
  assert.match(body, /<!-- louibot:12 -->/);
});

test("preserves a repository PR template before Louibot details", () => {
  const body = pullRequestBody(
    12,
    "Add the filter controls.",
    "npm test passed",
    "## Checklist\n\n- [ ] Reviewed the changes",
  );
  assert.match(body, /^## Checklist\n\n- \[ \] Reviewed the changes/);
  assert.ok(
    body.indexOf("## Checklist") < body.indexOf("## Implementation summary"),
  );
});

test("discovers the standard repository PR template locations", () => {
  const root = mkdtempSync(join(tmpdir(), "louibot-template-"));
  mkdirSync(join(root, ".github"), { recursive: true });
  writeFileSync(
    join(root, ".github", "pull_request_template.md"),
    "# PR checklist",
  );
  assert.equal(readPullRequestTemplate(root), "# PR checklist");
});

test("validation output cannot break the markdown fence", () => {
  assert.match(validationDetails("before ``` after"), /before ``\\` after/);
});

test("clarification and revision comments explain their action", () => {
  const clarification = clarificationComment([
    "Which items should be shown?",
    "Where should the control live?",
  ]);
  assert.match(clarification, /^## Clarification needed/m);
  assert.match(clarification, /1\. Which items should be shown\?/);
  assert.match(clarification, /2\. Where should the control live\?/);
  assert.match(clarification, /Generated by \[Louibot\]/);

  const revision = revisionComment(
    "Added the requested coverage.",
    "npm test passed",
  );
  assert.match(revision, /^## Revision published/m);
  assert.match(revision, /<summary>Validation results<\/summary>/);
  assert.match(revision, /Generated by \[Louibot\]/);
});
