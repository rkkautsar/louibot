import {
  Annotation,
  StateGraph,
  START,
  END,
  interrupt,
  Command,
} from "@langchain/langgraph";
import { SqliteSaver } from "@langchain/langgraph-checkpoint-sqlite";
import type { Config } from "./config.js";
import { Store, type Job, type JobStatus } from "./store.js";
import { GitHub } from "./github.js";
import { prepare, git, cleanup } from "./workspace.js";
import { code, type Result } from "./agent.js";
const State = Annotation.Root({
  job: Annotation<Job>(),
  result: Annotation<Result>(),
});
export function issuePhase(
  job: Job,
  stopped = false,
): "ready" | "blocked" | "done" | "closed" {
  if (job.status === "done")
    return job.outcome === "merged" ? "done" : "closed";
  return stopped ||
    ["clarification", "blocked", "failed", "stopped"].includes(job.status)
    ? "blocked"
    : "ready";
}

type ResumeInput = { text: string; events: string[] };

/** Keep model output safe for a single-line git subject and add one issue reference. */
export function commitSubject(
  issue: number,
  proposed: string | undefined,
  summary: string,
): string {
  const issueReference = `(#${issue})`;
  const withoutIssue = (proposed?.trim() || summary)
    .replace(/[\x00-\x1f\x7f]+/g, " ")
    .replace(new RegExp(`\\(\\s*#${issue}\\s*\\)|#${issue}(?![0-9])`, "g"), " ")
    .replace(/\s+/g, " ")
    .trim();
  const fallback = "Update implementation";
  const maxDescriptionLength = 70 - issueReference.length - 1;
  const subject = Array.from(withoutIssue || fallback)
    .slice(0, maxDescriptionLength)
    .join("")
    .trimEnd();
  return `${subject} ${issueReference}`;
}

async function clarificationReply(
  job: Job,
  github: GitHub,
): Promise<ResumeInput | undefined> {
  const latestQuestionId = Number(
    job.events
      .filter((event) => event.startsWith("question:"))
      .at(-1)
      ?.split(":")[1],
  );
  for (const comment of await github.comments(job.issue)) {
    if (
      comment.id > latestQuestionId &&
      !job.events.includes(`comment:${comment.id}`) &&
      (await github.authorized(comment.user.login))
    ) {
      return {
        text: comment.body,
        events: [...job.events, `comment:${comment.id}`],
      };
    }
  }
  return undefined;
}

async function reviewFeedback(
  job: Job,
  github: GitHub,
): Promise<{ resume?: ResumeInput }> {
  if (!job.pr) return {};
  const request = await github.revisionCommand(job.pr, job.events);
  return request
    ? {
        resume: {
          text: request.feedback,
          events: [...job.events, request.eventId, ...request.commentEvents],
        },
      }
    : {};
}

async function publishChanges(
  job: Job,
  result: Result,
  github: GitHub,
  saveJob: (job: Job, status: JobStatus) => Promise<Job>,
): Promise<Job> {
  const publishingJob = { ...job };
  await saveJob(publishingJob, "publishing");
  await git(publishingJob.worktree, ["add", "--all"]);
  const stagedFiles = await git(publishingJob.worktree, [
    "diff",
    "--cached",
    "--name-only",
  ]);
  if (stagedFiles.trim()) {
    await git(publishingJob.worktree, [
      "-c",
      "core.hooksPath=/dev/null",
      "commit",
      "-m",
      commitSubject(publishingJob.issue, result.commitMessage, result.summary),
    ]);
  }
  await git(publishingJob.worktree, [
    "-c",
    "core.hooksPath=/dev/null",
    "push",
    "origin",
    `HEAD:refs/heads/${publishingJob.branch}`,
  ]);
  const pullRequest =
    (await github.findPR(publishingJob.branch)) ??
    (await github.createPR(
      publishingJob.branch,
      publishingJob.title,
      `Generated by Louibot.\n\n${result.summary}\n\nValidation:\n${result.tests}\n\nCloses #${publishingJob.issue}\n\n<!-- louibot:${publishingJob.issue} -->`,
    ));
  publishingJob.pr = pullRequest.number;
  if (job.pr !== undefined) {
    await github.comment(
      pullRequest.number,
      `Louibot revised this PR.\n\n${result.summary}\n\nValidation:\n${result.tests}`,
      `louibot:revision:${publishingJob.issue}:${publishingJob.revision}`,
    );
  }
  return saveJob(publishingJob, "review");
}

export function workflow(
  root: string,
  config: Config,
  store: Store,
  github: GitHub,
  signal: AbortSignal,
) {
  const save = async (job: Job, status: JobStatus): Promise<Job> => {
    job.status = status;
    job.last = new Date().toISOString();
    store.save(job);
    store.log(job.issue, "state", status);
    try {
      await github.setIssuePhase(job.issue, issuePhase(job), config.github);
    } catch (error) {
      store.log(job.issue, "labels.error", String(error));
    }
    return job;
  };
  return new StateGraph(State)
    .addNode("implement", async ({ job }) => {
      const persistedJob = store.get(job.issue);
      const currentJob = {
        ...job,
        cost: Math.max(job.cost, persistedJob?.cost ?? 0),
      };
      if (store.stopped(currentJob.issue)) throw new Error("Job stopped");
      delete currentJob.error;
      await prepare(root, currentJob.worktree, currentJob.branch);
      await save(currentJob, "coding");
      const result = await code(config, currentJob, store, signal);
      return { job: currentJob, result };
    })
    .addNode("clarify", async ({ job, result }) => {
      const currentJob = { ...job };
      if (currentJob.rounds >= 3) {
        await save(currentJob, "blocked");
        return { job: currentJob };
      }
      const commentId = await github.comment(
        currentJob.issue,
        `Louibot needs clarification:\n\n${result.questions.join("\n\n")}`,
        `louibot:clarify:${currentJob.issue}:${currentJob.revision}`,
      );
      currentJob.events = [
        ...new Set([...currentJob.events, `question:${commentId}`]),
      ];
      await save(currentJob, "clarification");
      return { job: currentJob };
    })
    .addNode("wait", async ({ job }) => {
      const feedback = interrupt({ status: job.status, issue: job.issue }) as {
        text: string;
        events: string[];
      };
      const resumedJob = {
        ...job,
        feedback: feedback.text,
        events: feedback.events,
        revision: job.revision + 1,
        rounds: job.rounds + (job.status === "clarification" ? 1 : 0),
      };
      await save(resumedJob, "queued");
      return { job: resumedJob };
    })
    .addNode("publish", async ({ job, result }) => {
      const publishedJob = await publishChanges(job, result, github, save);
      return { job: publishedJob };
    })
    .addNode("blocked", async ({ job, result }) => ({
      job: await save({ ...job, error: result.summary }, "blocked"),
    }))
    .addEdge(START, "implement")
    .addConditionalEdges("implement", ({ result }) =>
      result.status === "done"
        ? "publish"
        : result.status === "clarify"
          ? "clarify"
          : "blocked",
    )
    .addConditionalEdges("clarify", ({ job }) =>
      job.status === "blocked" ? END : "wait",
    )
    .addEdge("publish", "wait")
    .addEdge("wait", "implement")
    .addEdge("blocked", END)
    .compile({
      checkpointer: SqliteSaver.fromConnString(`${store.dir}/workflow.sqlite`),
    });
}
type WorkflowGraph = ReturnType<typeof workflow>;
type WorkflowOptions = Parameters<WorkflowGraph["getState"]>[0];
type WorkflowSnapshot = Awaited<ReturnType<WorkflowGraph["getState"]>>;

function invocationOptions(job: Job, signal: AbortSignal): WorkflowOptions {
  return {
    configurable: { thread_id: `issue-${job.issue}` },
    signal,
    recursionLimit: 100,
  };
}

async function claimImplementationRequests(store: Store, github: GitHub) {
  for (const request of await github.implementationRequests()) {
    const issue = request.issue;
    store.claim({
      ...issue,
      issue: issue.number,
      status: "queued",
      branch: `louibot/issue-${issue.number}`,
      worktree: `${store.dir}/workspaces/${issue.number}`,
      revision: 0,
      cost: 0,
      last: new Date().toISOString(),
      events: [`implement:${request.commentId}`],
      feedback: "",
      rounds: 0,
    });
  }
}

async function restoreRetryFeedback(
  job: Job,
  store: Store,
  github: GitHub,
  snapshot: WorkflowSnapshot,
  graph: WorkflowGraph,
  options: WorkflowOptions,
): Promise<void> {
  const authorizedReplies: string[] = [];
  for (const comment of await github.comments(job.issue)) {
    if (
      job.events.includes(`comment:${comment.id}`) &&
      (await github.authorized(comment.user.login))
    ) {
      authorizedReplies.push(comment.body);
    }
  }
  if (authorizedReplies.length) job.feedback = authorizedReplies.join("\n\n");
  delete job.retryRequested;
  store.save(job);
  if (snapshot.next.length) await graph.updateState(options, { job });
}

async function reconcileCheckpoint(
  job: Job,
  isRetry: boolean,
  snapshot: WorkflowSnapshot,
  graph: WorkflowGraph,
  options: WorkflowOptions,
  store: Store,
): Promise<boolean> {
  const hasInterrupt = snapshot.tasks.some((task) => task.interrupts?.length);
  const checkpointJob = snapshot.values.job as Job | undefined;
  // Recover metadata after a crash between a graph checkpoint and the store write.
  if (!isRetry && checkpointJob && !snapshot.next.length && !hasInterrupt) {
    store.save(checkpointJob);
    return true;
  }
  // Complete a wait node if metadata was saved before shutdown but its checkpoint was not.
  if (
    !isRetry &&
    ["review", "clarification"].includes(job.status) &&
    snapshot.next.length > 0 &&
    !hasInterrupt
  ) {
    await graph.invoke(null, options);
    return true;
  }
  return false;
}

async function closeFinishedPullRequest(
  root: string,
  job: Job,
  config: Config,
  store: Store,
  github: GitHub,
): Promise<boolean> {
  if (!job.pr) return false;
  const pullRequest = await github.pr(job.pr);
  if (pullRequest.state.toLowerCase() !== "closed" && !pullRequest.mergedAt)
    return false;
  await cleanup(root, job.worktree, job.branch);
  job.status = "done";
  job.outcome = pullRequest.mergedAt ? "merged" : "closed";
  store.save(job);
  await github.setIssuePhase(job.issue, issuePhase(job), config.github);
  return true;
}

async function recordFailure(
  error: unknown,
  job: Job,
  config: Config,
  store: Store,
  github: GitHub,
  signal: AbortSignal,
): Promise<void> {
  if (signal.aborted && !store.stopped(job.issue)) {
    store.log(job.issue, "interrupted", String(error));
    return;
  }
  store.log(job.issue, "error", String(error));
  const currentJob = store.get(job.issue) ?? job;
  currentJob.status = store.stopped(job.issue) ? "stopped" : "failed";
  currentJob.error = String(error);
  store.save(currentJob);
  try {
    await github.setIssuePhase(job.issue, "blocked", config.github);
  } catch (labelError) {
    store.log(job.issue, "labels.error", String(labelError));
  }
}

async function processIssue(
  root: string,
  config: Config,
  store: Store,
  github: GitHub,
  graph: WorkflowGraph,
  job: Job,
  signal: AbortSignal,
): Promise<void> {
  if (signal.aborted) return;
  try {
    await github.setIssuePhase(
      job.issue,
      issuePhase(job, store.stopped(job.issue)),
      config.github,
    );
  } catch (error) {
    store.log(job.issue, "labels.error", String(error));
  }
  if (
    store.stopped(job.issue) ||
    ["done", "blocked", "failed"].includes(job.status)
  )
    return;

  const options = invocationOptions(job, signal);
  try {
    const snapshot = await graph.getState(options);
    const isRetry = job.retryRequested === true;
    if (isRetry)
      await restoreRetryFeedback(job, store, github, snapshot, graph, options);
    if (
      await reconcileCheckpoint(job, isRetry, snapshot, graph, options, store)
    ) {
      return;
    }
    if (await closeFinishedPullRequest(root, job, config, store, github))
      return;

    let resume: ResumeInput | undefined;
    if (job.status === "clarification") {
      resume = await clarificationReply(job, github);
      if (!resume) return;
    } else if (job.status === "review" && job.pr) {
      const feedback = await reviewFeedback(job, github);
      resume = feedback.resume;
      if (!resume) return;
    }

    if (isRetry || !resume) {
      await graph.invoke(snapshot.next.length ? null : { job }, options);
    } else {
      await graph.invoke(new Command({ resume }), options);
    }
  } catch (error) {
    await recordFailure(error, job, config, store, github, signal);
  }
}

export async function tick(
  root: string,
  config: Config,
  store: Store,
  signal: AbortSignal,
  githubClient?: GitHub,
): Promise<void> {
  store.registerSecret(
    config.endpoint ? process.env[config.endpoint.apiKeyEnv] : undefined,
  );
  const github = githubClient ?? new GitHub(config.repository);
  const graph = workflow(root, config, store, github, signal);
  await claimImplementationRequests(store, github);
  for (const job of store.all()) {
    if (signal.aborted) return;
    await processIssue(root, config, store, github, graph, job, signal);
  }
}
