const State = Annotation.Root({
  job: Annotation<Job>(),
  result: Annotation<Result>(),
  review: Annotation<ReviewResult | undefined>({
    value: (_current, next) => next,
    default: () => undefined,
  }),
});
export function issuePhase(
  job: Job,
  stopped = false,
): "ready" | "blocked" | "done" | "closed" {
  if (job.status === "done")
    return job.outcome === "merged" ? "done" : "closed";
  return stopped ||
    ["clarification", "blocked", "failed", "stopped"].includes(job.status)
    ? "blocked"
    : "ready";
}

type ResumeInput = { text: string; events: string[] };

const louibotAttribution =
  "_Generated by [Louibot](https://github.com/rkkautsar/louibot), a local-first issue implementer._";

function safeCodeBlock(value: string): string {
  return (value.trim() || "No validation output was recorded.").replaceAll(
    "```",
    "``\\`",
  );
}

export function validationDetails(tests: string): string {
  return `<details>\n<summary>Validation results</summary>\n\n\`\`\`text\n${safeCodeBlock(tests)}\n\`\`\`\n\n</details>`;
}

export interface RunMetadata {
  model?: string;
  reviewerModel?: string;
  reviewerMaxSteps?: number;
  reviewStatus?: Job["reviewStatus"];
  reviewSummary?: string;
  codingSeconds?: number;
  estimatedCostUsd?: number;
}

export function reviewerSkipSummary(error: unknown): string {
  if (
    error instanceof Error &&
    (error.name === "GraphRecursionError" ||
      /recursion limit/i.test(error.message))
  )
    return "Review stopped at its configured step limit; see local logs for the error details.";
  return "Review request failed; see local logs for the error details.";
}

export function formatDuration(seconds: number | undefined): string {
  const total = Math.max(0, Math.round(seconds ?? 0));
  const minutes = Math.floor(total / 60);
  const remaining = total % 60;
  if (minutes === 0) return `${remaining}s`;
  return `${minutes}m ${remaining}s`;
}

function runDetails(metadata?: RunMetadata): string {
  if (!metadata) return "";
  const cost =
    metadata.estimatedCostUsd === undefined
      ? "unavailable"
      : `$${metadata.estimatedCostUsd.toFixed(2)}`;
  return [
    "## Louibot run",
    "",
    `- Model: \`${metadata.model ?? "unknown"}\``,
    metadata.reviewerModel
      ? `- Independent review: \`${metadata.reviewerModel}\` (${metadata.reviewStatus === "findings" ? "findings returned to implementer; follow-up not independently re-reviewed" : (metadata.reviewStatus ?? "pending")}${metadata.reviewStatus === "skipped" && metadata.reviewerMaxSteps ? `; configured step limit: ${metadata.reviewerMaxSteps}` : ""})${metadata.reviewSummary ? ` — ${metadata.reviewSummary}` : ""}`
      : undefined,
    `- Agent time: ${formatDuration(metadata.codingSeconds)}`,
    `- Estimated spend: ${cost}`,
    "",
    "The spend is a controller-side reservation based on configured token rates; provider billing may differ.",
  ].join("\n");
}

export function pullRequestBody(
  issue: number,
  summary: string,
  tests: string,
  template?: string,
  metadata?: RunMetadata,
): string {
  const generated = [
    "## Implementation summary",
    "",
    summary.trim(),
    "",
    "## Validation",
    "",
    validationDetails(tests),
    "",
    runDetails(metadata),
    metadata ? "" : undefined,
    `Closes #${issue}`,
    "",
    "---",
    "",
    louibotAttribution,
    "",
    `<!-- louibot:${issue} -->`,
  ]
    .filter((line): line is string => line !== undefined)
    .join("\n");
  const preservedTemplate = template?.trim();
  return preservedTemplate
    ? `${preservedTemplate}\n\n---\n\n${generated}`
    : generated;
}

export function readPullRequestTemplate(root: string): string | undefined {
  const candidates = [
    ".github/pull_request_template.md",
    ".github/PULL_REQUEST_TEMPLATE.md",
    "pull_request_template.md",
    "PULL_REQUEST_TEMPLATE.md",
    "docs/pull_request_template.md",
    "docs/PULL_REQUEST_TEMPLATE.md",
  ];
  for (const relativePath of candidates) {
    const path = join(root, relativePath);
    if (existsSync(path)) return readFileSync(path, "utf8");
  }
  const directory = join(root, ".github", "PULL_REQUEST_TEMPLATE");
  if (existsSync(directory)) {
    const template = readdirSync(directory)
      .filter((name) => name.toLowerCase().endsWith(".md"))
      .sort()[0];
    if (template) return readFileSync(join(directory, template), "utf8");
  }
  return undefined;
}

export function clarificationComment(questions: string[]): string {
  return [
    "## Clarification needed",
    "",
    "I need a few product details before implementing this issue:",
    "",
    ...questions.map((question, index) => `${index + 1}. ${question.trim()}`),
    "",
    "Please reply with the decisions or examples that should guide the implementation.",
    "",
    "---",
    "",
    louibotAttribution,
  ].join("\n");
}

export function revisionComment(
  summary: string,
  tests: string,
  metadata?: RunMetadata,
): string {
  return [
    "## Revision published",
    "",
    summary.trim(),
    "",
    "## Validation",
    "",
    validationDetails(tests),
    "",
    runDetails(metadata),
    metadata ? "" : undefined,
    "---",
    "",
    louibotAttribution,
  ]
    .filter((line): line is string => line !== undefined)
    .join("\n");
}

function settleCodingTime(job: Job): void {
  if (!job.codingStartedAt) return;
  const started = Date.parse(job.codingStartedAt);
  if (Number.isFinite(started)) {
    job.codingSeconds =
      (job.codingSeconds ?? 0) + Math.max(0, (Date.now() - started) / 1000);
  }
  delete job.codingStartedAt;
}

/** Keep model output safe for a single-line git subject and add one issue reference. */
export function commitSubject(
  issue: number,
  proposed: string | undefined,
  summary: string,
): string {
  const issueReference = `(#${issue})`;
  const withoutIssue = (proposed?.trim() || summary)
    .replace(/[\x00-\x1f\x7f]+/g, " ")
    .replace(new RegExp(`\\(\\s*#${issue}\\s*\\)|#${issue}(?![0-9])`, "g"), " ")
    .replace(/\s+/g, " ")
    .trim();
  const fallback = "Update implementation";
  const maxDescriptionLength = 70 - issueReference.length - 1;
  const subject = Array.from(withoutIssue || fallback)
    .slice(0, maxDescriptionLength)
    .join("")
    .trimEnd();
  return `${subject} ${issueReference}`;
}

async function clarificationReply(
  job: Job,
  github: GitHub,
): Promise<ResumeInput | undefined> {
  const latestQuestionId = Number(
    job.events
      .filter((event) => event.startsWith("question:"))
      .at(-1)
      ?.split(":")[1],
  );
  for (const comment of await github.comments(job.issue)) {
    if (
      comment.id > latestQuestionId &&
      !job.events.includes(`comment:${comment.id}`) &&
      (await github.authorized(comment.user.login))
    ) {
      return {
        text: comment.body,
        events: [...job.events, `comment:${comment.id}`],
      };
    }
  }
  return undefined;
}

async function reviewFeedback(
  job: Job,
  github: GitHub,
): Promise<{ resume?: ResumeInput }> {
  if (!job.pr) return {};
  const request = await github.revisionCommand(job.pr, job.events);
  return request
    ? {
        resume: {
          text: request.feedback,
          events: [...job.events, request.eventId, ...request.commentEvents],
        },
      }
    : {};
}

async function publishChanges(
  job: Job,
  result: Result,
  github: GitHub,
  reviewerMaxSteps: number,
  saveJob: (job: Job, status: JobStatus) => Promise<Job>,
): Promise<Job> {
  const publishingJob = { ...job };
  await saveJob(publishingJob, "publishing");
  await git(publishingJob.worktree, ["add", "--all"]);
  const stagedFiles = await git(publishingJob.worktree, [
    "diff",
    "--cached",
    "--name-only",
  ]);
  if (stagedFiles.trim()) {
    await git(publishingJob.worktree, [
      "-c",
      "core.hooksPath=/dev/null",
      "commit",
      "-m",
      commitSubject(publishingJob.issue, result.commitMessage, result.summary),
    ]);
  }
  await git(publishingJob.worktree, [
    "-c",
    "core.hooksPath=/dev/null",
    "push",
    "origin",
    `HEAD:refs/heads/${publishingJob.branch}`,
  ]);
  const pullRequest =
    (await github.findPR(publishingJob.branch)) ??
    (await github.createPR(
      publishingJob.branch,
      publishingJob.title,
      pullRequestBody(
        publishingJob.issue,
        result.summary,
        result.tests,
        readPullRequestTemplate(publishingJob.worktree),
        {
          model: publishingJob.model,
          reviewerModel: publishingJob.reviewerModel,
          reviewerMaxSteps,
          reviewStatus: publishingJob.reviewStatus,
          reviewSummary: publishingJob.reviewSummary,
          codingSeconds: publishingJob.codingSeconds,
          estimatedCostUsd: publishingJob.cost,
        },
      ),
    ));
  publishingJob.pr = pullRequest.number;
  if (job.pr !== undefined) {
    await github.comment(
      pullRequest.number,
      revisionComment(result.summary, result.tests, {
        model: publishingJob.model,
        reviewerModel: publishingJob.reviewerModel,
        reviewerMaxSteps,
        reviewStatus: publishingJob.reviewStatus,
        reviewSummary: publishingJob.reviewSummary,
        codingSeconds: publishingJob.codingSeconds,
        estimatedCostUsd: publishingJob.cost,
      }),
      `louibot:revision:${publishingJob.issue}:${publishingJob.revision}`,
    );
  }
  return saveJob(publishingJob, "review");
}

export function workflow(
  root: string,
  config: Config,
  store: Store,
  github: GitHub,
  signal: AbortSignal,
) {
  const save = async (job: Job, status: JobStatus): Promise<Job> => {
    job.status = status;
    job.last = new Date().toISOString();
    store.save(job);
    store.log(job.issue, "state", status);
    try {
      await github.setIssuePhase(job.issue, issuePhase(job), config.github);
    } catch (error) {
      store.log(job.issue, "labels.error", String(error));
    }
    return job;
  };
  return new StateGraph(State)
    .addNode("implement", async ({ job }) => {
      const persistedJob = store.get(job.issue);
      const currentJob = {
        ...job,
        cost: Math.max(job.cost, persistedJob?.cost ?? 0),
        codingSeconds: Math.max(
          job.codingSeconds ?? 0,
          persistedJob?.codingSeconds ?? 0,
        ),
      };
      if (store.stopped(currentJob.issue)) throw new Error("Job stopped");
      delete currentJob.error;
      await prepare(root, currentJob.worktree, currentJob.branch);
      settleCodingTime(currentJob);
      currentJob.codingStartedAt = new Date().toISOString();
      await save(currentJob, "coding");
      let result: Result;
      try {
        result = await code(config, currentJob, store, signal);
      } finally {
        settleCodingTime(currentJob);
        store.save(currentJob);
      }
      return { job: currentJob, result };
    })
    .addNode("independentReview", async ({ job, result }) => {
      const currentJob = { ...job };
      if (store.stopped(currentJob.issue) || signal.aborted)
        throw new Error("Job stopped");
      await save(currentJob, "reviewing");
      if (!config.reviewer.enabled) {
        currentJob.reviewedRevision = currentJob.revision;
        currentJob.reviewStatus = "skipped";
        currentJob.reviewSummary = "Review disabled before this revision ran.";
        store.save(currentJob);
        return {
          job: currentJob,
          review: {
            status: "pass",
            summary: currentJob.reviewSummary,
            findings: [],
          } satisfies ReviewResult,
        };
      }
      try {
        await git(currentJob.worktree, ["add", "--all"]);
        const changedFiles = await git(currentJob.worktree, [
          "diff",
          "--cached",
          "--name-only",
        ]);
        const fullDiff = await git(currentJob.worktree, [
          "diff",
          "--cached",
          "--no-ext-diff",
          "--unified=4",
        ]);
        const diffLimit = 48_000;
        const diff =
          fullDiff.length <= diffLimit
            ? fullDiff
            : `${fullDiff.slice(0, diffLimit)}\n\n[Diff excerpt truncated; inspect the changed files in the read-only workspace.]`;
        const review = await reviewImplementation(
          config,
          currentJob,
          store,
          signal,
          {
            changedFiles: changedFiles || "No staged files",
            diff: diff || "No staged diff",
            implementation: result,
          },
        );
        currentJob.reviewedRevision = currentJob.revision;
        currentJob.reviewStatus = review.status;
        currentJob.reviewSummary = review.summary
          .replace(/[\r\n`]/g, " ")
          .slice(0, 400);
        currentJob.reviewerModel = config.reviewer.model ?? config.model;
        currentJob.reviewerFeedback =
          review.status === "findings"
            ? JSON.stringify(review.findings, null, 2)
            : undefined;
        store.save(currentJob);
        store.log(currentJob.issue, "review.result", review);
        return { job: currentJob, review };
      } catch (error) {
        if (signal.aborted || store.stopped(currentJob.issue)) throw error;
        currentJob.reviewedRevision = currentJob.revision;
        currentJob.reviewStatus = "skipped";
        currentJob.reviewSummary = reviewerSkipSummary(error);
        currentJob.reviewerModel = config.reviewer.model ?? config.model;
        delete currentJob.reviewerFeedback;
        store.save(currentJob);
        store.log(currentJob.issue, "review.skipped", String(error));
        return {
          job: currentJob,
          review: {
            status: "pass",
            summary: currentJob.reviewSummary,
            findings: [],
          } satisfies ReviewResult,
        };
      }
    })
    .addNode("clarify", async ({ job, result }) => {
      const currentJob = { ...job };
      if (currentJob.rounds >= 3) {
        await save(currentJob, "blocked");
        return { job: currentJob };
      }
      const commentId = await github.comment(
        currentJob.issue,
        clarificationComment(result.questions),
        `louibot:clarify:${currentJob.issue}:${currentJob.revision}`,
      );
      currentJob.events = [
        ...new Set([...currentJob.events, `question:${commentId}`]),
      ];
      await save(currentJob, "clarification");
      return { job: currentJob };
    })
    .addNode("wait", async ({ job }) => {
      const feedback = interrupt({ status: job.status, issue: job.issue }) as {
        text: string;
        events: string[];
      };
      const resumedJob = {
        ...job,
        feedback: feedback.text,
        events: feedback.events,
        revision: job.revision + 1,
        rounds: job.rounds + (job.status === "clarification" ? 1 : 0),
        reviewerFeedback: undefined,
      };
      await save(resumedJob, "queued");
      return { job: resumedJob };
    })
    .addNode("publish", async ({ job, result }) => {
      const publishedJob = await publishChanges(
        job,
        result,
        github,
        config.reviewer.maxSteps,
        save,
      );
      return { job: publishedJob };
    })
    .addNode("blocked", async ({ job, result }) => ({
      job: await save({ ...job, error: result.summary }, "blocked"),
    }))
    .addEdge(START, "implement")
    .addConditionalEdges("implement", ({ job, result }) => {
      if (result.status === "clarify") return "clarify";
      if (result.status !== "done") return "blocked";
      return config.reviewer.enabled && job.reviewedRevision !== job.revision
        ? "independentReview"
        : "publish";
    })
    .addConditionalEdges("independentReview", ({ review }) =>
      review?.status === "findings" ? "implement" : "publish",
    )
    .addConditionalEdges("clarify", ({ job }) =>
      job.status === "blocked" ? END : "wait",
    )
    .addEdge("publish", "wait")
    .addEdge("wait", "implement")
    .addEdge("blocked", END)
    .compile({
      checkpointer: SqliteSaver.fromConnString(`${store.dir}/workflow.sqlite`),
    });
}
type WorkflowGraph = ReturnType<typeof workflow>;
type WorkflowOptions = Parameters<WorkflowGraph["getState"]>[0];
type WorkflowSnapshot = Awaited<ReturnType<WorkflowGraph["getState"]>>;

export async function runWithConcurrency<T>(
  items: T[],
  limit: number,
  run: (item: T) => Promise<void>,
): Promise<void> {
  let next = 0;
  const worker = async () => {
    while (true) {
      const index = next++;
      if (index >= items.length) return;
      await run(items[index]);
    }
  };
  const results = await Promise.allSettled(
    Array.from({ length: Math.min(limit, items.length) }, worker),
  );
  const failure = results.find(
    (result): result is PromiseRejectedResult => result.status === "rejected",
  );
  if (failure) throw failure.reason;
}

function invocationOptions(job: Job, signal: AbortSignal): WorkflowOptions {
  return {
    configurable: {
      thread_id: `issue-${job.issue}-attempt-${job.attempt ?? 1}`,
    },
    signal,
    recursionLimit: 100,
  };
}

export async function claimImplementationRequests(
  store: Store,
  github: GitHub,
  config: Config,
) {
  for (const request of await github.implementationRequests()) {
    const issue = request.issue;
    const existing = store.get(issue.number);
    if (!existing) {
      store.claim({
        ...issue,
        issue: issue.number,
        status: "queued",
        branch: `louibot/issue-${issue.number}`,
        worktree: `${store.dir}/workspaces/${issue.number}`,
        revision: 0,
        attempt: 1,
        model: config.model,
        reviewerModel: config.reviewer.enabled
          ? (config.reviewer.model ?? config.model)
          : undefined,
        cost: 0,
        codingSeconds: 0,
        last: new Date().toISOString(),
        events: [`implement:${request.commentId}`],
        feedback: "",
        rounds: 0,
      });
      continue;
    }
    const event = `implement:${request.commentId}`;
    if (existing.events.includes(event)) continue;
    if (["failed", "blocked", "stopped"].includes(existing.status)) {
      const retried = store.retry(issue.number, event);
      store.save({
        ...retried,
        ...issue,
        issue: issue.number,
        last: new Date().toISOString(),
      });
      continue;
    }
    if (existing.status !== "done" || existing.outcome !== "closed") continue;
    const attempt = (existing.attempt ?? 1) + 1;
    store.save({
      ...existing,
      ...issue,
      issue: issue.number,
      status: "queued",
      branch: `louibot/issue-${issue.number}-retry-${attempt}`,
      worktree: `${store.dir}/workspaces/${issue.number}-retry-${attempt}`,
      revision: 0,
      attempt,
      pr: undefined,
      model: config.model,
      reviewerModel: config.reviewer.enabled
        ? (config.reviewer.model ?? config.model)
        : undefined,
      reviewedRevision: undefined,
      reviewStatus: undefined,
      reviewSummary: undefined,
      reviewerFeedback: undefined,
      cost: 0,
      codingSeconds: 0,
      codingStartedAt: undefined,
      last: new Date().toISOString(),
      events: [...existing.events, event],
      feedback: "",
      rounds: 0,
      retryRequested: undefined,
      error: undefined,
      outcome: undefined,
    });
    store.log(issue.number, "state", "queued");
  }
}

async function restoreRetryFeedback(
  job: Job,
  store: Store,
  github: GitHub,
  snapshot: WorkflowSnapshot,
  graph: WorkflowGraph,
  options: WorkflowOptions,
): Promise<void> {
  const authorizedReplies: string[] = [];
  for (const comment of await github.comments(job.issue)) {
    if (
      job.events.includes(`comment:${comment.id}`) &&
      (await github.authorized(comment.user.login))
    ) {
      authorizedReplies.push(comment.body);
    }
  }
  if (authorizedReplies.length) job.feedback = authorizedReplies.join("\n\n");
  delete job.retryRequested;
  store.save(job);
  if (snapshot.next.length) await graph.updateState(options, { job });
}

async function reconcileCheckpoint(
  job: Job,
  isRetry: boolean,
  snapshot: WorkflowSnapshot,
  graph: WorkflowGraph,
  options: WorkflowOptions,
  store: Store,
): Promise<boolean> {
  const hasInterrupt = snapshot.tasks.some((task) => task.interrupts?.length);
  const checkpointJob = snapshot.values.job as Job | undefined;
  // Recover metadata after a crash between a graph checkpoint and the store write.
  if (!isRetry && checkpointJob && !snapshot.next.length && !hasInterrupt) {
    store.save(checkpointJob);
    return true;
  }
  // Complete a wait node if metadata was saved before shutdown but its checkpoint was not.
  if (
    !isRetry &&
    ["review", "clarification"].includes(job.status) &&
    snapshot.next.length > 0 &&
    !hasInterrupt
  ) {
    await graph.invoke(null, options);
    return true;
  }
  return false;
}

async function closeFinishedPullRequest(
  root: string,
  job: Job,
  config: Config,
  store: Store,
  github: GitHub,
): Promise<boolean> {
  if (!job.pr) return false;
  const pullRequest = await github.pr(job.pr);
  if (pullRequest.state.toLowerCase() !== "closed" && !pullRequest.mergedAt)
    return false;
  await cleanup(root, job.worktree);
  job.status = "done";
  job.outcome = pullRequest.mergedAt ? "merged" : "closed";
  store.save(job);
  await github.setIssuePhase(job.issue, issuePhase(job), config.github);
  return true;
}

async function recordFailure(
  error: unknown,
  job: Job,
  config: Config,
  store: Store,
  github: GitHub,
  signal: AbortSignal,
): Promise<void> {
  if (signal.aborted && !store.stopped(job.issue)) {
    store.log(job.issue, "interrupted", String(error));
    return;
  }
  store.log(job.issue, "error", String(error));
  const currentJob = store.get(job.issue) ?? job;
  currentJob.status = store.stopped(job.issue) ? "stopped" : "failed";
  currentJob.error = String(error);
  store.save(currentJob);
  try {
    await github.setIssuePhase(job.issue, "blocked", config.github);
  } catch (labelError) {
    store.log(job.issue, "labels.error", String(labelError));
  }
}

async function processIssue(
  root: string,
  config: Config,
  store: Store,
  github: GitHub,
  job: Job,
  signal: AbortSignal,
): Promise<void> {
  if (signal.aborted) return;
  try {
    await github.setIssuePhase(
      job.issue,
      issuePhase(job, store.stopped(job.issue)),
      config.github,
    );
  } catch (error) {
    store.log(job.issue, "labels.error", String(error));
  }
  if (
    store.stopped(job.issue) ||
    ["done", "blocked", "failed"].includes(job.status)
  )
    return;

  if (signal.aborted || store.stopped(job.issue)) return;
  const options = invocationOptions(job, signal);
  try {
    const graph = workflow(root, config, store, github, signal);
    const snapshot = await graph.getState(options);
    const isRetry = job.retryRequested === true;
    if (isRetry)
      await restoreRetryFeedback(job, store, github, snapshot, graph, options);
    if (
      await reconcileCheckpoint(job, isRetry, snapshot, graph, options, store)
    ) {
      return;
    }
    if (await closeFinishedPullRequest(root, job, config, store, github))
      return;

    if (job.status === "publishing") {
      // Publication side effects are idempotent: resume the pending node so a
      // crash after push or PR creation cannot strand the job in this state.
      await graph.invoke(snapshot.next.length ? null : { job }, options);
      return;
    }

    let resume: ResumeInput | undefined;
    if (job.status === "clarification") {
      resume = await clarificationReply(job, github);
      if (!resume) return;
    } else if (job.status === "review" && job.pr) {
      const feedback = await reviewFeedback(job, github);
      resume = feedback.resume;
      if (!resume) return;
    }

    if (isRetry || !resume) {
      await graph.invoke(snapshot.next.length ? null : { job }, options);
    } else {
      await graph.invoke(new Command({ resume }), options);
    }
  } catch (error) {
    await recordFailure(error, job, config, store, github, signal);
  }
}

export async function tick(
  root: string,
  config: Config,
  store: Store,
  signal: AbortSignal,
  githubClient?: GitHub,
): Promise<void> {
  store.registerSecret(
    config.endpoint ? process.env[config.endpoint.apiKeyEnv] : undefined,
  );
  const github = githubClient ?? new GitHub(config.repository);
  await claimImplementationRequests(store, github, config);
  const jobs = store.all();
  if (!jobs.length || signal.aborted) return;

  const active = new Map<number, AbortController>();
  const abortAll = () => {
    for (const controller of active.values()) controller.abort();
  };
  const stopMonitor = setInterval(() => {
    for (const [issue, controller] of active) {
      if (store.stopped(issue)) controller.abort();
    }
  }, 250);
  signal.addEventListener("abort", abortAll, { once: true });

  try {
    await runWithConcurrency(
      jobs,
      config.agent.maxConcurrentJobs,
      async (job) => {
        if (signal.aborted) return;
        const controller = new AbortController();
        active.set(job.issue, controller);
        if (store.stopped(job.issue)) controller.abort();
        try {
          await processIssue(
            root,
            config,
            store,
            github,
            job,
            controller.signal,
          );
        } finally {
          active.delete(job.issue);
        }
      },
    );
  } finally {
    clearInterval(stopMonitor);
    signal.removeEventListener("abort", abortAll);
    abortAll();
  }
}
